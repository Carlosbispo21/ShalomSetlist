import { test, expect } from '@playwright/test';

test('cifras podem ser inseridas, movidas, editadas, persistidas e apagadas sem afetar rabiscos', async ({ page, context }, info) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Explorar com exemplos' }).click();
  await page.getByRole('button', { name: /^Exemplo 01/ }).click();
  await page.locator('.pdf-page[data-active=true] .page-loading').waitFor({ state: 'hidden' });
  // Rabisco preexistente deve sobreviver à inclusão e à exclusão de cifras.
  await page.getByRole('button', { name: 'Caneta', exact: true }).click();
  const rect = (await page.locator('.pdf-page[data-active=true]').boundingBox())!;
  await page.mouse.move(rect.x + rect.width * .4, rect.y + rect.height * .35);
  await page.mouse.down(); await page.mouse.move(rect.x + rect.width * .5, rect.y + rect.height * .36); await page.mouse.up();
  await expect(page.locator('.ink-layer polyline')).toHaveCount(1);
  await page.getByRole('button', { name: 'Cifras', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Caneta', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await page.mouse.click(rect.x + rect.width * .80, rect.y + rect.height * .42);
  await expect(page.getByRole('dialog', { name: 'Adicionar cifra' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Exemplo 01' })).toBeVisible();
  await page.getByLabel('Texto da cifra').fill('Dó♯ / Am');
  await page.getByLabel('Tamanho da fonte').fill('19.5');
  await page.getByRole('button', { name: 'Salvar cifra' }).click();
  let note = page.getByRole('button', { name: 'Editar cifra Dó♯ / Am', exact: true });
  await expect(note).toBeVisible();
  const initial = await note.getAttribute('transform');
  const box = (await note.boundingBox())!;
  await page.mouse.move(box.x + 9, box.y + 9); await page.mouse.down();
  await page.mouse.move(box.x - 30, box.y + 40, { steps: 6 }); await page.mouse.up();
  await expect(note).not.toHaveAttribute('transform', initial!);
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const moved = await note.getAttribute('transform');
  await note.click();
  await page.getByLabel('Texto da cifra').fill('Fá♯');
  await page.getByLabel('Tamanho da fonte').fill('28');
  await page.getByRole('button', { name: 'Salvar cifra' }).click();
  note = page.getByRole('button', { name: 'Editar cifra Fá♯', exact: true });
  await expect(note).toHaveAttribute('transform', moved!);
  const initialFont = Number(await note.locator('text').getAttribute('font-size'));
  expect(initialFont).toBeGreaterThan(28);
  await page.getByRole('button', { name: 'Aumentar zoom' }).click();
  await expect(note).toHaveAttribute('transform', moved!);
  await page.getByRole('button', { name: 'Diminuir zoom' }).click();
  await page.screenshot({ path: `artifacts/${info.project.name}-cifras.png` });
  await page.getByRole('button', { name: 'Voltar ao repertório' }).click();
  await context.setOffline(true);
  await page.getByRole('button', { name: /^Exemplo 01/ }).click();
  await expect(page.locator('.text-note text')).toHaveText('Fá♯');
  await expect(page.locator('.ink-layer polyline')).toHaveCount(1);
  await page.getByRole('button', { name: 'Cifras', exact: true }).click();
  await page.getByRole('button', { name: 'Editar cifra Fá♯', exact: true }).click();
  await expect(page.getByLabel('Tamanho da fonte')).toHaveValue('28');
  await page.getByLabel('Texto da cifra').fill('Rascunho');
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await expect(page.locator('.text-note text')).toHaveText('Fá♯');
  await page.getByRole('button', { name: 'Editar cifra Fá♯', exact: true }).click();
  await page.getByRole('button', { name: 'Excluir cifra' }).click();
  await expect(page.locator('.text-note')).toHaveCount(0);
  await expect(page.locator('.ink-layer polyline')).toHaveCount(1);
  await page.getByRole('button', { name: 'Voltar ao repertório' }).click();
  await page.getByRole('button', { name: /^Exemplo 01/ }).click();
  await expect(page.locator('.text-note')).toHaveCount(0);
  await expect(page.locator('.ink-layer polyline')).toHaveCount(1);
});

test('cifras da segunda página sobrevivem à mudança de hino no modo contínuo', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Explorar com exemplos' }).click();
  await page.getByRole('button', { name: /^Exemplo 01/ }).click();
  await page.getByRole('button', { name: 'Próxima página' }).click();
  await page.locator('.pdf-page[data-active=true] .page-loading').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Cifras', exact: true }).click();
  const rect = (await page.locator('.pdf-page[data-active=true]').boundingBox())!;
  await page.mouse.click(rect.x + rect.width * .4, rect.y + rect.height * .45);
  await page.getByLabel('Texto da cifra').fill('Sol\nRé');
  await page.getByRole('button', { name: 'Salvar cifra' }).click();
  await page.getByRole('button', { name: 'Cifras', exact: true }).click();
  await page.getByRole('button', { name: 'Contínua' }).click();
  await page.getByRole('button', { name: 'Próximo hino', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Exemplo 02' })).toBeVisible();
  await page.getByRole('button', { name: 'Hino anterior', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Exemplo 01' })).toBeVisible();
  await expect(page.locator('[data-page="1"] .text-note')).toHaveCount(0);
  await expect(page.locator('[data-page="2"] .text-note tspan')).toHaveText(['Sol', 'Ré']);
  await expect(page.locator('.reader-scroll')).toHaveJSProperty('scrollTop', 0);
});
