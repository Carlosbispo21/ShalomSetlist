import { test, expect } from '@playwright/test';
import { PDFDocument } from 'pdf-lib';

test('exemplos, PDF, caneta persistente, metrônomo e leitura offline', async ({ page, context }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Repertório' })).toBeVisible();
  await page.getByRole('button', { name: 'Explorar com exemplos' }).click();
  await expect(page.getByText('Você está explorando partituras de exemplo.')).toBeVisible();
  await page.evaluate(() => window.scrollTo(0,0));
  await page.screenshot({ path: `artifacts/${testInfo.project.name}-repertorio.png`, fullPage: true });
  await page.getByRole('button', { name: /^Exemplo 01/ }).click();
  await expect(page.getByLabel('Partitura, página 1')).toBeVisible();
  await page.getByRole('button', { name: 'Próxima página' }).click();
  await expect(page.getByLabel('Partitura, página 2')).toBeVisible();
  await page.getByRole('button', { name: 'Página anterior' }).click();
  const initialWidth = (await page.locator('.pdf-page').boundingBox())!.width;
  await page.getByRole('button', { name: 'Aumentar zoom' }).click();
  await expect.poll(async () => (await page.locator('.pdf-page').boundingBox())!.width).toBeGreaterThan(initialWidth);
  await page.getByRole('button', { name: 'Diminuir zoom' }).click();
  await page.getByRole('button', { name: 'Caneta', exact: true }).click();
  const ink = page.locator('.ink-layer'); const rect = (await ink.boundingBox())!;
  await page.mouse.move(rect.x + 80, rect.y + 120); await page.mouse.down();
  await page.mouse.move(rect.x + 140, rect.y + 150, { steps: 8 }); await page.mouse.up();
  await expect(ink.locator('polyline')).toHaveCount(1);
  await page.getByRole('button', { name: 'Abrir metrônomo' }).click();
  await page.getByLabel('Batidas por minuto').fill('');
  await page.getByLabel('Batidas por minuto').pressSequentially('96');
  await expect(page.getByLabel('Batidas por minuto')).toHaveValue('96');
  await page.getByRole('button', { name: 'Iniciar', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Pausar', exact: true })).toBeVisible();
  await expect.poll(() => page.getByTestId('beat-dot').getAttribute('class'), { intervals: [20] }).toContain('lit');
  await page.screenshot({ path: `artifacts/${testInfo.project.name}-leitor.png` });
  await page.getByRole('button', { name: 'Ocultar controles' }).click();
  await expect(page.locator('.metronome')).toHaveCSS('width', '44px');
  await expect.poll(() => page.getByTestId('beat-dot').getAttribute('class'), { intervals: [20] }).toContain('lit');
  await page.getByRole('button', { name: 'Mostrar controles' }).click();
  await page.getByRole('button', { name: 'Voltar ao repertório' }).click();
  await page.getByRole('button', { name: /^Exemplo 01/ }).click();
  await expect(page.locator('.ink-layer polyline')).toHaveCount(1);
  await page.getByRole('button', { name: 'Contínua' }).click();
  await expect(page.locator('.pdf-page')).toHaveCount(2);
  await page.getByRole('button', { name: 'Voltar ao repertório' }).click();
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Repertório' })).toBeVisible();
  await context.setOffline(true);
  await page.reload();
  await page.getByRole('button', { name: /^Exemplo 01/ }).click();
  await expect(page.getByLabel('Partitura, página 1')).toBeVisible();
  await expect(page.locator('.ink-layer polyline')).toHaveCount(1);
  expect(errors).toEqual([]);
});

test('importa PDF real, filtra por grupo e rejeita PDF inválido', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Adicionar partituras', exact: true }).click();
  const pdf = await PDFDocument.create(); pdf.addPage(); pdf.addPage();
  await page.getByLabel('Selecionar PDFs').setInputFiles({ name:'Hino de teste.pdf',mimeType:'application/pdf',buffer:Buffer.from(await pdf.save()) });
  await page.getByLabel('Grupo', { exact: true }).selectOption('Irmãs');
  await page.getByRole('button', { name:'Salvar neste aparelho' }).click();
  await expect(page.getByRole('button', { name:/^Hino de teste/ })).toBeVisible();
  await page.getByRole('button', { name:'Crianças', exact:true }).click();
  await expect(page.getByRole('button', { name:/^Hino de teste/ })).toHaveCount(0);
  await page.getByRole('button', { name:'Irmãs', exact:true }).click();
  await expect(page.getByRole('button', { name:/^Hino de teste/ })).toBeVisible();
  await page.getByRole('button', { name: 'Adicionar partituras', exact: true }).click();
  await page.getByLabel('Selecionar PDFs').setInputFiles({ name:'invalido.pdf',mimeType:'application/pdf',buffer:Buffer.from('not a pdf') });
  await page.getByRole('button', { name:'Salvar neste aparelho' }).click();
  await expect(page.getByRole('alert')).toContainText('PDF inválido');
});

test('limpa os hinos ao começar a segunda-feira de São Paulo', async ({ page }) => {
  await page.clock.install({ time:new Date('2026-10-11T23:58:00-03:00') });
  await page.goto('/');
  await page.getByRole('button', { name:'Explorar com exemplos' }).click();
  await expect(page.getByRole('button', { name:/^Exemplo 01/ })).toBeVisible();
  await page.clock.setSystemTime(new Date('2026-10-12T00:01:00-03:00'));
  await page.clock.runFor(61000);
  await expect(page.getByRole('button', { name:/^Exemplo 01/ })).toHaveCount(0);
  await expect(page.getByText('Você está explorando partituras de exemplo.')).toHaveCount(0);
});
